"""Phase-1 report for category A (Phase 1 report contents). Everything is computed from data/v1 files.

Writes results/<YYYY-MM-DD>/REPORT_A.md (English), report_A.json and CSV tables; each table lists the command that
reproduces it.
"""
from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

from ..core.instance import PKG_ROOT, data_root, load_index, load_private
from ..core.splits import load_manifest

STATUS_ZH = {"pass": "pass", "fail": "fail", "tool_error": "tool error", "unsupported": "unsupported", "timeout": "timeout",
             "crash": "crash", "unavailable": "unavailable", "unverified": "unverified"}
TRACK_ZH = {"a2a_2q": "Main track: all-to-all two-qubit gate count", "line_2q": "Linear connectivity two-qubit gate count",
            "grid_2q": "Grid connectivity two-qubit gate count", "codespace_a2a_2q": "codespace_state all-to-all two-qubit gate count"}


def _read_jsonl(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()] if p.exists() else []


def _write_csv(path: Path, header: list[str], rows: list[list]) -> None:
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def make_report(out_dir: Path | None = None, log=print) -> str:
    out = out_dir or (PKG_ROOT / "results" / date.today().isoformat())
    out.mkdir(parents=True, exist_ok=True)
    man = load_manifest("A")
    idx = {r["id"]: r for r in load_index("A")}
    split_of = {e["id"]: s for s, es in man["splits"].items() for e in es}
    recs = _read_jsonl(data_root() / "baselines" / "A" / "records.jsonl")
    best = _read_jsonl(data_root() / "baselines" / "A" / "best_known.jsonl")
    opt = _read_jsonl(data_root() / "optimal" / "A.jsonl")
    published = _read_jsonl(data_root() / "published" / "A.jsonl")
    rep: dict = {"date": date.today().isoformat(), "totals": man["totals"]}
    md: list[str] = []
    add = md.append

    # ---------------- 1. counts per split x family x size bin
    counts = defaultdict(Counter)
    for iid, s in split_of.items():
        r = idx[iid]
        counts[s][(r["family"], r["size_bin"])] += 1
    rows = []
    for s in ("train", "val", "test_in", "test_ood", "probe"):
        for (fam, b), c in sorted(counts[s].items()):
            rows.append([s, fam, b, c])
    _write_csv(out / "A_counts.csv", ["split", "family", "size_bin", "count"], rows)
    rep["counts"] = rows
    add("## 1. Instances per split (by family and size bin)\n")
    add("Reproduce: `qbank generate A` (table generated by `qbank report A` from `data/v1/splits/A.json`, CSV: `A_counts.csv`)\n")
    add("| Split | Family | Size bin | Count |\n|---|---|---|---|")
    for r in rows:
        add(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} |")
    add(f"\nTotal: " + ", ".join(f"{s} {man['totals'][s]}" for s in man["totals"]) + f"; {sum(man['totals'].values())} in all.\n")

    # ---------------- 2. share of instances where each tool is (co-)best, per track
    by_it = defaultdict(list)
    for r in recs:
        by_it[(r["instance_id"], r["track"])].append(r)
    share = defaultdict(Counter)
    n_inst = Counter()
    for (iid, track), rs in by_it.items():
        ok = [r for r in rs if r["status"] == "pass"]
        if not ok:
            continue
        m = min(r["costs"]["two_qubit_gates"] for r in ok)
        n_inst[track] += 1
        for tool in sorted({r["tool"] for r in ok if r["costs"]["two_qubit_gates"] == m}):
            share[track][tool] += 1
    add("## 2. Share of instances on which each tool is the best baseline, per track\n")
    add("Definition: for each (instance, track), take the verified baseline records with the smallest two-qubit gate count; on ties each "
        "tied tool is counted once, so a column can sum to more than 100%. "
        "Externally released circuits (`published:*`, `qecirc:*`) also count as tools. Reproduce: `qbank baselines A && qbank import A && qbank aggregate A && qbank report A` "
        "(CSV: `A_best_tool_share.csv`)\n")
    rows = []
    for track in sorted(share):
        add(f"### {TRACK_ZH.get(track, track)} ({n_inst[track]} instances)\n")
        add("| Tool | Instances where best (including ties) | Share |\n|---|---|---|")
        for tool, c in share[track].most_common():
            add(f"| {tool} | {c} | {100 * c / n_inst[track]:.1f}% |")
            rows.append([track, tool, c, n_inst[track], round(100 * c / n_inst[track], 2)])
        add("")
    _write_csv(out / "A_best_tool_share.csv", ["track", "tool", "best_count", "instances", "percent"], rows)
    rep["best_tool_share"] = rows

    # ---------------- 3. probe: gap of best baseline to optimum
    add("## 3. Gap of the best baseline to the optimum on probe\n")
    add("Definitions: `cnot_model_optimum` is the optimum of MQT QECC exact synthesis in the CNOT model (|0⟩/|+⟩ initialization + CNOTs only), "
        "counted as a proven optimum only when the solver reports proven_optimal; "
        "it is an upper bound on the optimum over general Clifford circuits, so the gap here is a lower bound on the true gap. "
        "`clifford_completion_upper_bound` is the optimum found by QMAP SAT (two-qubit gate objective) for one particular Clifford completion "
        "of the state; it is only an upper bound for the state (other tools use fewer gates on existing instances) and is not counted as a proven optimum. "
        "`lower_bound_attained` is an analytic lower bound (an n-qubit GHZ state needs ≥ n−1 two-qubit gates). "
        "Reproduce: `qbank optimal A && qbank aggregate A && qbank report A` (CSV: `A_probe_gap.csv`)\n")
    bk = {(b["instance_id"], b["track"]): b for b in best}
    opt_by = defaultdict(list)
    for o in opt:
        opt_by[o["instance_id"]].append(o)
    rows = []
    add("| Instance | n | Best baseline (two-qubit gates) | Source | Optimum/lower bound | Kind | Proven | Gap |\n|---|---|---|---|---|---|---|---|")
    for e in man["splits"]["probe"]:
        iid = e["id"]
        b = bk.get((iid, "a2a_2q"), {})
        bb = b.get("best_baseline_value")
        for o in sorted(opt_by.get(iid, []), key=lambda o: o["kind"]):
            if o.get("value") is None:
                rows.append([iid, idx[iid]["n"], bb, b.get("source"), None, o["kind"], o.get("proven"), None, o.get("status")])
                add(f"| {iid} | {idx[iid]['n']} | {bb} | {b.get('source')} | - | {o['kind']} ({o.get('status')}) | - | - |")
                continue
            gap = None if bb is None else bb - o["value"]
            rows.append([iid, idx[iid]["n"], bb, b.get("source"), o["value"], o["kind"], o.get("proven"), gap, ""])
            add(f"| {iid} | {idx[iid]['n']} | {bb} | {b.get('source')} | {o['value']} | {o['kind']} | {o.get('proven')} | {gap} |")
        if not opt_by.get(iid):
            rows.append([iid, idx[iid]["n"], bb, b.get("source"), None, "none", None, None, "no optimum computed"])
            add(f"| {iid} | {idx[iid]['n']} | {bb} | {b.get('source')} | - | not computed | - | - |")
    _write_csv(out / "A_probe_gap.csv", ["instance", "n", "best_baseline", "best_source", "optimum", "kind", "proven", "gap", "note"], rows)
    rep["probe_gap"] = rows
    gaps = [r for r in rows if r[7] is not None and r[6]]
    if gaps:
        z = sum(1 for r in gaps if r[7] == 0)
        add(f"\nSummary: {len(gaps)} probe entries have a proven optimum or lower bound; the best baseline reaches the optimum on {z} "
            f"({100 * z / len(gaps):.0f}%), mean gap {sum(r[7] for r in gaps) / len(gaps):.2f} two-qubit gates, maximum gap {max(r[7] for r in gaps)}. "
            "Note: the \"optimum\" here is mostly the proven optimum in the CNOT model (|0⟩/|+⟩ initialization + CNOTs only), which is only an "
            "upper bound for general Clifford circuits.\n")

    # ---------------- 4. best baseline already optimal (all splits)
    add("## 4. Instances where the best baseline already reaches the optimum (all splits)\n")
    add("Reproduce as above (CSV: `A_baseline_at_optimum.csv`)\n")
    rows = []
    for o in opt:
        if o.get("value") is None or not o.get("proven"):
            continue
        b = bk.get((o["instance_id"], "a2a_2q"), {})
        bb = b.get("best_baseline_value")
        if bb is not None and bb == o["value"]:
            rows.append([o["instance_id"], split_of.get(o["instance_id"]), o["value"], o["kind"], b.get("source")])
    add("| Instance | Split | Value | Optimum kind | Best baseline source |\n|---|---|---|---|---|")
    for r in rows:
        add(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} |")
    _write_csv(out / "A_baseline_at_optimum.csv", ["instance", "split", "value", "kind", "best_source"], rows)
    rep["baseline_at_optimum"] = rows

    # ---------------- 5. unavailable / timeout / crash / unsupported
    add("\n## 5. Unavailable, crash, timeout and unsupported list\n")
    add("Aggregated by (tool, track, status); individual records in `data/v1/baselines/A/records.jsonl`. (CSV: `A_non_pass.csv`)\n")
    c = Counter()
    examples = {}
    for r in recs:
        if r["status"] != "pass":
            k = (r["tool"], r["track"], r["status"])
            c[k] += 1
            examples.setdefault(k, (r["instance_id"], r.get("reason", "")[:160]))
    add("| Tool | Track | Status | Count | Example instance | Reason (excerpt) |\n|---|---|---|---|---|---|")
    rows = []
    for (tool, track, st), cnt in sorted(c.items(), key=lambda kv: (-kv[1], kv[0])):
        ex = examples[(tool, track, st)]
        add(f"| {tool} | {track} | {STATUS_ZH.get(st, st)} | {cnt} | {ex[0]} | {ex[1].replace('|', '/')} |")
        rows.append([tool, track, st, cnt, ex[0], ex[1]])
    _write_csv(out / "A_non_pass.csv", ["tool", "track", "status", "count", "example_instance", "reason"], rows)
    rep["non_pass"] = rows

    # ---------------- 6. published values
    add("\n## 6. Published records (with references)\n")
    add("\"Reproduced\" means the paper released circuits that were each verified by this benchmark's checkers and recounted under these definitions (the `published:*` baseline records); otherwise \"reported value only\". (CSV: `A_published.csv`)\n")
    add("| Instance | Value | Reference | Semantics | Counts toward best_known | Reproduced (these definitions) |\n|---|---|---|---|---|---|")
    rows = []
    for p in published:
        rp = [r for r in recs if r["instance_id"] == p["instance_id"] and r["track"] == "a2a_2q" and r["tool"].startswith("published:")
              and r["status"] == "pass"]
        repro = min((r["costs"]["two_qubit_gates"] for r in rp), default=None)
        ref = p["reference"]
        add(f"| {p['instance_id']} | {p['value']} | {ref['arxiv']} {ref['location']} | {p['semantics'][:60]} | "
            f"{'yes' if p['eligible_for_best_known'] else 'no'} | {repro if repro is not None else 'reported value only'} |")
        rows.append([p["instance_id"], p["value"], ref["arxiv"], ref["location"], p["eligible_for_best_known"], repro])
    _write_csv(out / "A_published.csv", ["instance", "value", "arxiv", "location", "eligible", "reproduced_value"], rows)

    from .extras import all_extras
    md.append("")
    md.append(all_extras("A", out))
    text = "# qbank v1 - Category A (stabilizer state / code state preparation) Phase 1 report\n\n" + f"Generated: {date.today().isoformat()}. " \
           "This report is generated entirely by `qbank report A` from the files in `data/v1/`.\n\n" + "\n".join(md) + "\n"
    (out / "REPORT_A.md").write_text(text, encoding="utf-8")
    (out / "report_A.json").write_text(json.dumps(rep, indent=1, ensure_ascii=False, default=str) + "\n", encoding="utf-8")
    return str(out / "REPORT_A.md")
