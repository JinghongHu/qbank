"""Overall report: results/<date>/REPORT.md, computed from data/v1 and the per-category reports."""
from __future__ import annotations

import json
import platform
from collections import Counter
from datetime import date
from pathlib import Path

from ..core.canon import file_sha256
from ..core.instance import PKG_ROOT, data_root
from ..core.splits import is_frozen, load_manifest

CATS = ("A", "B", "C", "D")
NAME = {"A": "stabilizer state / code state preparation", "B": "classical-function oracle compilation",
        "C": "routing and commuting-gate scheduling", "D": "non-Clifford state preparation"}


def _jsonl(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()] if p.exists() else []


def make_overall(out_dir: Path | None = None, log=print) -> str:
    out = out_dir or (PKG_ROOT / "results" / date.today().isoformat())
    out.mkdir(parents=True, exist_ok=True)
    L = ["# qbank v1 overall report\n", f"Generated: {date.today().isoformat()}. Generated by `qbank report all` from `data/v1/`; the detailed "
         "per-category reports are `REPORT_<C>.md` in the same directory, the datasheets are `data/v1/<C>/DATASHEET.md`.\n"]
    L.append("## 1. Size and splits\n")
    L.append("| Category | Content | train | val | test_in | test_ood | probe | Total | Splits frozen |\n|---|---|---|---|---|---|---|---|---|")
    tot = Counter()
    for c in CATS:
        try:
            m = load_manifest(c)
        except FileNotFoundError:
            continue
        t = m["totals"]
        tot.update(t)
        L.append(f"| {c} | {NAME[c]} | {t['train']} | {t['val']} | {t['test_in']} | {t['test_ood']} | {t['probe']} | "
                 f"{sum(t.values())} | {'yes' if is_frozen(c) else 'no'} |")
    L.append(f"| Total | | {tot['train']} | {tot['val']} | {tot['test_in']} | {tot['test_ood']} | {tot['probe']} | {sum(tot.values())} | |\n")
    L.append("## 2. Baselines\n")
    L.append("Each (instance, tool, track) gets 60 s of single-core wall-clock time; all outputs are verified by this benchmark's checkers and recounted by the costs module.")
    L.append("| Category | Baseline records | Pass | Fail | Timeout | Unsupported | Tool error | Unverified | Crash/unavailable | (instance, track) with best_known | No verified baseline |\n"
             "|---|---|---|---|---|---|---|---|---|---|---|")
    for c in CATS:
        recs = _jsonl(data_root() / "baselines" / c / "records.jsonl")
        best = _jsonl(data_root() / "baselines" / c / "best_known.jsonl")
        if not recs:
            L.append(f"| {c} | (not aggregated yet) | | | | | | | | | |")
            continue
        s = Counter(r["status"] for r in recs)
        L.append(f"| {c} | {len(recs)} | {s['pass']} | {s['fail']} | {s['timeout']} | {s['unsupported']} | {s['tool_error']} | "
                 f"{s['unverified'] + s['checker_disagreement']} | {s['crash'] + s['unavailable']} | "
                 f"{sum(1 for b in best if b.get('value') is not None)} | {sum(1 for b in best if b.get('value') is None)} |")
    L.append("\n## 3. Known optima and lower bounds\n")
    L.append("| Category | Records | Proven optimum | Lower bound | Numerical optimum (unproven) | Upper bound/constructed value | Best baseline reaches the (proven) optimum |\n|---|---|---|---|---|---|---|")
    for c in CATS:
        opt = _jsonl(data_root() / "optimal" / f"{c}.jsonl")
        if not opt:
            continue
        best = {(b["instance_id"], b["track"]): b.get("best_baseline_value") for b in _jsonl(data_root() / "baselines" / c / "best_known.jsonl")}
        kinds = Counter()
        at = 0
        for o in opt:
            k = o.get("kind") or ("optimal" if str(o.get("status", "")).startswith("optimal") else
                                  "lower_bound" if o.get("kind") == "lower_bound" else "upper_bound")
            if c == "A":
                k = "optimal" if o.get("proven") and o.get("value") is not None else "upper_bound"
            if c == "C":
                k = "optimal" if o.get("kind") == "optimal" and o.get("proven") else "upper_bound"
            if o.get("kind") == "numerical_optimum":
                k = "numerical_optimum"
            kinds[k] += 1
            bb = best.get((o["instance_id"], o.get("track", "a2a_2q")))
            if k == "optimal" and bb is not None and o.get("value") is not None and bb == o["value"]:
                at += 1
        L.append(f"| {c} | {len(opt)} | {kinds['optimal']} | {kinds['lower_bound']} | {kinds['numerical_optimum']} | "
                 f"{kinds['upper_bound']} | {at} |")
    L.append("\n(The CNOT-model optimum of category A is an upper bound on the general Clifford optimum; the optimal SWAP counts of QUBIKOS in category C are constructed values, not independently verified, and are counted as \"upper bound/constructed value\".)\n")
    L.append("## 4. Contracts and checkers (summary)\n")
    for line in (
        "- A: two checkers, stim and an independent GF(2) tableau, with signs; single-qubit Pauli corrections are free and appended explicitly. The known optima are optima in the CNOT model and only upper bounds for general Clifford circuits.",
        "- B: bit-parallel exhaustive check (including phases) up to 22 qubits; beyond that a CaDiCaL SAT miter (600 s); non-±1 phases beyond the limit are judged unverified.",
        "- C: mapping replay (topological reordering of the DAG), plus a QCEC second check up to 16 qubits; the commuting-block track allows reordering within blocks.",
        "- D: support-aware sparse state-vector simulation, fidelity ≥ 1 − 1e−9; plus a qiskit Statevector second check up to 16 qubits.",
        "- Every external tool call has a timeout; \"unverified\" never counts as correct; disagreement between two checkers is judged \"checker disagreement\"."):
        L.append(line)
    L.append("\n## 5. Environment and reproducibility\n")
    lock = PKG_ROOT / "requirements.lock.txt"
    L.append(f"- Python {platform.python_version()} (`qbank/.venv`, official PyPI, hash-locked: `requirements.lock.txt` sha256 `{file_sha256(lock)[:16]}...`).")
    L.append("- Isolated builds: Rust toolchain (`external/rust`), rustiq @ 42500022 (seed patch), ABC @ ab2139ee, OLSQ2 @ 0d7066f4 (Qiskit 2 patch). Patches stored in `env/patches/`.")
    L.append("- External data: `data/v1/external/fetch_{A,B,C}.sh` refetches the original sources by commit and sha256.")
    L.append("- One-command rebuild: `bash rebuild_all.sh` (environment → external data → `qbank rebuild all` → tests).")
    fz = data_root() / "splits" / "FROZEN.sha256"
    if fz.exists():
        L.append("- Frozen split manifests (`data/v1/splits/FROZEN.sha256`):\n```\n" + fz.read_text().strip() + "\n```")
    L.append("\n## 6. Known limitations\n")
    L.append("See the \"Known limitations\" section of each category's DATASHEET (`data/v1/<C>/DATASHEET.md`).")
    p = out / "REPORT.md"
    p.write_text("\n".join(L) + "\n", encoding="utf-8")
    # machine-readable summary (REPORT.md + report.json + CSV tables)
    summary = {"date": date.today().isoformat(), "categories": {}}
    for c in CATS:
        try:
            m = load_manifest(c)
        except FileNotFoundError:
            continue
        recs = _jsonl(data_root() / "baselines" / c / "records.jsonl")
        best = _jsonl(data_root() / "baselines" / c / "best_known.jsonl")
        rp = data_root() / "baselines" / c / "repro.json"
        summary["categories"][c] = {
            "version": m.get("qbank_version"), "frozen": is_frozen(c), "totals": m["totals"],
            "baseline_records": len(recs), "status_counts": dict(Counter(r["status"] for r in recs)),
            "best_known_pairs": len(best), "best_known_missing": sum(1 for b in best if b.get("value") is None),
            "repro": ({k: v for k, v in json.loads(rp.read_text()).items() if k != "rows"} if rp.exists() else None)}
    (out / "report.json").write_text(json.dumps(summary, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return str(p)
